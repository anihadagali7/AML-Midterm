import experiment as e,json
from pathlib import Path
rows=[json.loads(x) for x in Path('experiments/trials.jsonl').read_text().splitlines()];ok=[r for r in rows if r['status']=='ok'];configs=[]
for scale in ['standard','global']:
 for C in [.03,.05,.2,.3,.5,2,3,30]:configs.append(dict(model='logistic',scale=scale,C=C))
 for C in [1,3,10,30]:
  for gamma in [.0001,.0003,.0005,.002,.005]:configs.append(dict(model='svc',scale=scale,C=C,gamma=gamma))
for C in [1,3,30,100]:
 for scale in ['global','raw']:configs.append(dict(model='logistic',scale=scale,norm=True,C=C))
for alpha in [.001,.01,.1,1]:
 for gamma in [.0003,.001,.003,.01]:configs.append(dict(model='krr',alpha=alpha,gamma=gamma))
for amplitude in [1,10]:
 for length in [5,10,20,40]:configs.append(dict(model='gp',amplitude=amplitude,length=length))
for pc in [2,3,5]:configs.append(dict(model='qda',pca=pc,reg=.9))
for pc in [5,15,30]:
 for k in [3,7]:configs.append(dict(model='nca',pca=30,components=pc,k=k))
# Refine graph geometry, especially sharper local neighborhoods and less noisy dimensions.
for pc in [5,10,15,40]:
 for k in [3,7,12]:configs.append(dict(model='graph',pca=pc,k=k,alpha=.8))
for scale in ['global','raw']:
 for norm in [True,False]:
  for k in [3,7,15]:configs.append(dict(model='graph',scale=scale,norm=norm,k=k,alpha=.9))
for typ in ['kmeans','gmm']:
 for pc in [5,10,50]:
  for n in [5,15,35]:configs.append(dict(model='cluster',cluster=typ,pca=pc,clusters=n))
# Pseudo-labels generated by graph or density-cluster teachers; small weight prevents false labels dominating.
teachers=[max([r for r in ok if r['model']==t],key=lambda r:r['score'])['config'] for t in ['graph','cluster']]
teachers.append(dict(model='cluster',cluster='kmeans',clusters=12,pca=25))
for teacher in teachers:
 for student in ['svc','logistic']:
  for weight in [.05,.2,.5]:
   for confidence in [.8,.95]:configs.append(dict(model='pseudo',teacher=teacher,student=student,C=10 if student=='svc' else .1,gamma=.001,pseudo_weight=weight,confidence=confidence,labelwise=True))
e.save_json('experiments/refine-input.json',configs)
